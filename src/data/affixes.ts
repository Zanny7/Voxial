export type AffixOrigin = "greek" | "latin";

export type AffixType = "prefix" | "suffix" | "both";

export type AffixExample = {
  word: string;
  explanation: string;
};

export type Affix = {
  id: string;
  origin: AffixOrigin;
  type: AffixType;
  text: string;
  displayText: string;
  shortDescription: string;
  example: AffixExample;
};

function defineAffix(
  id: string,
  origin: AffixOrigin,
  type: AffixType,
  text: string,
  displayText: string,
  shortDescription: string,
  word: string,
  explanation: string,
): Affix {
  return {
    id,
    origin,
    type,
    text,
    displayText,
    shortDescription,
    example: {
      word,
      explanation,
    },
  };
}

